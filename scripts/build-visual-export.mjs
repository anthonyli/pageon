import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const root = new URL('../', import.meta.url);
const result = await build({
  absWorkingDir: root.pathname, entryPoints: ['packages/runtime/src/visual-export-entry.js'],
  bundle: true, write: false, format: 'iife', globalName: 'PageOnVisualExport', platform: 'browser',
  target: 'es2020', supported: { 'template-literal': false }, minify: true, legalComments: 'none', charset: 'ascii',
});
const require = createRequire(new URL('../packages/runtime/package.json', import.meta.url));
const license = await readFile(new URL('./LICENSE', `file://${require.resolve('html-to-image/package.json')}`), 'utf8');
const source = `(function(){/*! html-to-image\n${license}\n*/\n${result.outputFiles[0].text}\nreturn PageOnVisualExport.createVisualExporter;})()`;
await writeFile(new URL('packages/runtime/src/visual-export-bundle.js', root),
  `// Generated by scripts/build-visual-export.mjs. Offline renderer and PDF writer.\nexport const VISUAL_EXPORT_FACTORY_SOURCE = ${JSON.stringify(source.replace(/<\/script/gi, '<\\/script'))};\n`);
console.log(`Offline visual exporter: ${Buffer.byteLength(source)} bytes`);
